"""Domain-specific contracts implemented by Galbot SDK adapters."""
from typing import Any, Protocol, Sequence


class NavigationPort(Protocol):
    def capabilities(self) -> list[str]: ...
    def snapshot(self) -> dict[str, Any]: ...
    def navigate_to_goal(self, pose: Sequence[float], collision_check: bool, timeout: float) -> Any: ...
    def navigate_to_goal_v2(self, pose: Sequence[float], max_velocity: Sequence[float], frame_id: str, collision_check: bool, timeout: float, omni_plan: bool) -> Any: ...
    def set_navigation_target(self, pose: Sequence[float], frame_id: str, speed_ratio: float, collision_check: bool) -> Any: ...
    def navigate_through_waypoints(self, poses: Sequence[Sequence[float]], frame_id: str, collision_check: bool) -> Any: ...
    def navigate_along_trajectory(self, poses: Sequence[Sequence[float]], frame_id: str, speed_ratio: float, collision_check: bool) -> Any: ...
    def navigate_with_velocity(self, vx: float, vy: float, vyaw: float, duration: float, collision_check: bool) -> Any: ...
    def check_path_reachability(self, goal: Sequence[float], current: Sequence[float]) -> bool: ...
    def navigation_target_status(self, task_id: str) -> str: ...
    def navigation_path(self, task_id: str) -> dict[str, Any]: ...
    def stop(self) -> Any: ...
    def relocalize(self, pose: Sequence[float]) -> Any: ...
    def move_straight_to(self, pose: Sequence[float], timeout: float) -> Any: ...


class RobotPort(Protocol):
    def capabilities(self) -> list[str]: ...
    def snapshot(self, include_lidar: bool = False, lidar_options: dict[str, Any] | None = None, include_sensors: bool = False, include_joints: bool = True) -> dict[str, Any]: ...
    def camera_frame(self, source: str, last_timestamp_ns: int | None = None, preview_depth: bool = True) -> dict[str, Any]: ...
    def controller_snapshot(self, group: str) -> dict[str, Any]: ...
    def switch_controller(self, controller: str) -> Any: ...
    def set_base_velocity(self, linear: Sequence[float], angular: Sequence[float], duration: float) -> Any: ...
    def emergency_stop(self) -> Any: ...
    def resume_from_emergency_stop(self) -> Any: ...
    def stop_controller(self, group: str) -> Any: ...


class MotionPort(Protocol):
    def capabilities(self) -> list[str]: ...
    def plan(self, request: dict[str, Any]) -> dict[str, Any]: ...
    def execute(self, plan: dict[str, Any], speed_rad_s: float, start_tolerance_rad: float) -> dict[str, Any]: ...
    def move_end_effector_offset(self, arm: str, offset: Sequence[float], rpy: Sequence[float] | None = None) -> Any: ...
    def end_effector_pose(self, arm: str) -> list[float]: ...
